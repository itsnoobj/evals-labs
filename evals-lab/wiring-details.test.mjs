// Run: node evals-lab/wiring-details.test.mjs
import assert from 'node:assert/strict';
import { CASES, CARDS, CATEGORY_LABELS, perfectRun } from './cases.js';
import { METRICS, scoreRun } from './engine.js';
import { SYSTEM_PROMPT } from './agent-step.js';
import { NODE_IDS } from './wiring-graph.js';
import { buildDetails, dspyHtml, CHECKER_RULES } from './wiring-details.js';
import { verifyRun } from './guarded-agent.js';
import { INPUT_RULES, OUTPUT_RULES } from './guardrails.js';

let n = 0;
const ok = (c, m) => { assert.ok(c, m); n++; };
const has = (h, s, m) => ok(h.includes(s), m ?? `missing: ${s}`);
const lacks = (h, s, m) => ok(!h.includes(s), m ?? `unexpected: ${s}`);

const c = CASES[0];
const cardNames = Object.fromEntries(Object.entries(CARDS).map(([id, v]) => [id, v.name]));
const run = perfectRun(c);
const scores = scoreRun(c, run);
const verdict = verifyRun(c, run);
const shared = { c, cases: CASES, cardNames, labels: CATEGORY_LABELS, metrics: METRICS, modelName: 'M', mode: 'replay', recordedTemp: 0.7, promptTab: 'ours', dspy: null };
const side = { steps: run.steps, modelSteps: run.steps, attempts: [{ steps: run.steps, verdict }], events: [], outcome: 'passed_first_try', pending: false, scores };

// every node has a panel; the simple agent's missing nodes say so
const careful = buildDetails('careful', side, shared);
const simple = buildDetails('simple', { ...side, attempts: [{ steps: run.steps, verdict: null }], outcome: null }, shared);
for (const id of NODE_IDS.careful) ok(typeof careful[id] === 'string' && careful[id].length > 20, `careful panel ${id}`);
for (const id of NODE_IDS.simple) ok(typeof simple[id] === 'string' && simple[id].length > 20, `simple panel ${id}`);
for (const id of ['dataset', 'key', 'checks', 'bar', 'trace', 'eval', 'card', 'gate']) has(simple[id], 'MISSING', `simple ${id} is missing`);

// content
has(careful.dataset, CASES[5].query.slice(0, 20)); // the tools list at the end of every panel has its own <li> items, so count only before it
ok((careful.dataset.split('<details class="stage-tools"')[0].match(/<li>/g) ?? []).length === 6, 'six golden questions');
has(careful.key, 'ICICI Amazon Pay or HDFC Swiggy'.split(' or ').sort().join(' or ') === 'HDFC Swiggy or ICICI Amazon Pay' ? 'HDFC Swiggy or ICICI Amazon Pay' : 'x', 'tie names');
has(careful.key, '₹750'); has(careful.key, 'Amazon.in'); has(careful.key, 'class="cardsmx');
has(careful.checks, METRICS[0].label); for (const r of CHECKER_RULES) has(careful.checks, r.slice(0, 30));
has(careful.bar, 'Ship only if all 7 automatic checks pass');
has(careful.ask, 'Prime member');
has(careful.model, '0.2'); has(simple.model, '0.7'); has(careful.model, 'ON'); has(simple.model, 'OFF');
has(careful.t1, 'classify_merchant'); has(careful.t1, '800 ms'); has(careful.t1, '60');
has(careful.c1, 'PASS'); has(careful.answer, 'HDFC Swiggy'); has(careful.trace, '&quot;tool&quot;');
has(careful.eval, 'Correct final answer'); has(careful.card, 'PASS'); has(careful.gate, 'Ship');

// prompts: simple shows the exact prompt, careful has two tabs; the DSPy tab never says it is what the agent sent
has(simple.prompt, SYSTEM_PROMPT.slice(0, 40).replace(/&/g, '&amp;'));
has(careful.prompt, 'Our prompt'); has(careful.prompt, 'DSPy prompt'); has(careful.prompt, 'JSON schema');
const dsp = buildDetails('careful', side, { ...shared, promptTab: 'dspy', dspy: { status: 'loading' } }).prompt;
has(dsp, 'Loading the DSPy prompt');
const failed = buildDetails('careful', side, { ...shared, promptTab: 'dspy', dspy: { status: 'error', error: 'HTTP 404' } }).prompt;
has(failed, 'could not be loaded'); has(failed, 'HTTP 404');
const fake = { status: 'ok', data: { dspyVersion: '9.9.9', note: 'a <b>note</b>', variants: [
  { id: 'zero-shot-react', label: 'Zero', messages: [{ role: 'system', content: 'SYS <x>' }, { role: 'user', content: 'USR' }] },
  { id: 'few-shot', label: 'Few', messages: [{ role: 'system', content: 'S2' }, { role: 'user', content: 'U2' }] }] } };
const dh = dspyHtml(fake);
has(dh, 'Generated by real DSPy 9.9.9 with a recording fake model'); has(dh, 'The live agent uses the shorter prompt in the other tab');
has(dh, 'SYS &lt;x&gt;'); lacks(dh, 'SYS <x>'); has(dh, 'a &lt;b&gt;note&lt;/b&gt;'); has(dh, 'characters');

// escaping of run text
const evil = { ...side, steps: run.steps.map((s) => (s.kind === 'final' ? { ...s, reply: '<img src=x onerror=1>' } : s)) };
const ev = buildDetails('careful', evil, shared);
lacks(ev.answer, '<img'); lacks(ev.draft, '<img'); lacks(ev.trace, '<img');

// a failing score names the failing checks in the gate
const bad = { ...scores, task_success: { pass: false, reason: 'wrong' } };
const g = buildDetails('careful', { ...side, scores: bad }, shared).gate;
has(g, 'Blocked'); has(g, 'Correct final answer');

// a typed question (checks not run, none failed) is "Cannot decide", not "Blocked"
const nk = { ...scores, task_success: { pass: null, reason: 'no answer key for your own question' } };
const g2 = buildDetails('careful', { ...side, scores: nk }, shared).gate;
has(g2, 'Cannot decide'); lacks(g2, 'Blocked');

// pending: nothing invented
const pend = buildDetails('careful', { ...side, steps: [], attempts: [{ steps: [], verdict: null }], pending: true, scores: null }, shared);
has(pend.t1, 'Not reached yet'); has(pend.c3, 'reads the run when this try ends'); has(pend.gate, 'Not decided yet');


// AI grader: own node with the flow picture; the 8 checks and checks panels only point to it
ok(careful.judge.includes('You are a strict grader'), 'judge: grader system prompt');
has(careful.judge, 'Question: ' + c.query.replace(/'/g, '&#39;'), 'judge: user message built from this run');
has(careful.judge, 'NOT ASKED'); has(careful.judge, 'data-hook="judge-flow"'); has(careful.judge, 'Second opinion only');
lacks(careful.judge, '&amp;lt;', 'judge: not double escaped');
for (const k of ['eval', 'checks']) {
  lacks(careful[k], 'You are a strict grader', `${k}: no duplicate prompt`);
  has(careful[k], 'Click the AI grader box to see how it works', `${k}: pointer`);
}
has(simple.judge, 'MISSING'); has(simple.judge, 'Nothing here'); lacks(simple.judge, 'strict grader');
ok(!simple.eval.includes('strict grader'), 'simple agent has no grader panel');
// open-source tools: every real (careful) panel has them once, MISSING boxes have none
for (const id of NODE_IDS.careful) {
  has(careful[id], 'Open-source tools for this step', `careful ${id} has tools`);
  ok(careful[id].split('class="stage-tools"').length === 2, `careful ${id}: tools list exactly once`);
}
for (const id of NODE_IDS.simple) {
  const missing = simple[id].includes('<b>MISSING</b>');
  if (missing) lacks(simple[id], 'Open-source tools for this step', `simple missing ${id} has no tools`);
  else has(simple[id], 'Open-source tools for this step', `simple real ${id} has tools`);
}
has(careful.trace, 'https://github.com/langfuse/langfuse'); lacks(simple.trace, 'langfuse');
for (const [kind, d] of [['careful', careful], ['simple', simple]]) {
  const all = Object.values(d).join('');
  ok(!/\sid="/.test(all), `${kind}: panels add no id attributes, so no duplicate ids`);
}

// input guardrail panel
const gEv = [{ t: 'guard_in_ok', attempt: 0, text: 'Input guardrails passed: 4 rules' }];
const guardOk = buildDetails('careful', { ...side, events: gEv }, shared).guard;
for (const r of INPUT_RULES) { has(guardOk, r.label); has(guardOk, r.plain.replace(/'/g, '&#39;')); }
ok((guardOk.match(/<b class="wd-ok">PASS<\/b>/g) ?? []).length === 5, 'verdict line + 4 rules read PASS');
lacks(guardOk, 'BLOCKED');
has(guardOk, 'After the answer (output guardrails)');
for (const r of OUTPUT_RULES) { has(guardOk, r.label); has(guardOk, r.plain.replace(/'/g, '&#39;')); }
const guardBad = buildDetails('careful', { ...side, steps: [], attempts: [{ steps: [], verdict: null }], outcome: 'blocked',
  events: [{ t: 'guard_in_fail', attempt: 0, rule: 'prompt_injection', text: 'This tries to change the <b>agent</b>.' }] }, shared).guard;
const states = INPUT_RULES.map((r) => new RegExp(`<b class="wd-(\\w+)">([A-Z ]+)</b> <b>${r.label}</b>`).exec(guardBad)?.slice(1, 3).join(':'));
ok(JSON.stringify(states) === JSON.stringify(['ok:PASS', 'ok:PASS', 'bad:BLOCKED', 'off:NOT RUN']), `per-rule words: ${states}`);
has(guardBad, 'The model never ran'); has(guardBad, 'This tries to change the &lt;b&gt;agent&lt;/b&gt;.'); lacks(guardBad, '<b>agent</b>');
has(buildDetails('careful', side, shared).guard, 'The rules have not run yet');
has(buildDetails('careful', { ...side, pending: true }, shared).guard, 'before the model starts');
// simple agent: a dashed MISSING box
has(simple.guard, 'MISSING'); has(simple.guard, 'Nothing here'); lacks(simple.guard, INPUT_RULES[0].label);
// c3 lists the output guardrails and counts the output check
has(careful.c3, 'Output guardrails (part of this check)');
for (const r of OUTPUT_RULES) has(careful.c3, r.label);
has(careful.c3, 'Output guardrails passed');
const c3Bad = buildDetails('careful', { ...side, attempts: [{ steps: run.steps, verdict: { ok: false, problems: ['Output guardrail: The answer promised a guaranteed result.'], checks: [{ id: 'output', ok: false, label: 'Output guardrails passed' }] } }] }, shared).c3;
has(c3Bad, 'FAIL'); has(c3Bad, 'Output guardrail: The answer promised a guaranteed result.');

// a typed question has no answer key: nothing crashes, the key panel says so
const typed = { ...c, id: 'CUSTOM', custom: true, expected: null, expectedTrajectory: null };
for (const kind of ['careful', 'simple']) {
  let d;
  try { d = buildDetails(kind, side, { ...shared, c: typed }); } catch (err) { d = null; console.error(err); }
  ok(d !== null && NODE_IDS[kind].every((id) => typeof d[id] === 'string'), `${kind}: typed question builds every panel`);
}
has(buildDetails('careful', side, { ...shared, c: typed }).key, 'No answer key for your own question');
console.log(`${n} checks passed`);
