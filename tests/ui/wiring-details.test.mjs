// Run: node tests/ui/wiring-details.test.mjs
import assert from "node:assert/strict";
import { CASES, CARDS, CATEGORY_LABELS, perfectRun } from "../../evals-lab/src/task/cases.js";
import { METRICS, scoreRun } from "../../evals-lab/src/evals/engine.js";
import { SYSTEM_PROMPT } from "../../evals-lab/src/agent/agent-step.js";
import { NODE_IDS } from "../../evals-lab/src/ui/wiring-graph.js";
import { buildDetails, buildExplain, dspyHtml, CHECKER_RULES } from "../../evals-lab/src/ui/wiring-details.js";
import { explainHtml } from "../../evals-lab/src/ui/explain-dialog.js";
import { verifyRun } from "../../evals-lab/src/agent/guarded-agent.js";
import { INPUT_RULES, OUTPUT_RULES } from "../../evals-lab/src/agent/guardrails.js";

let n = 0;
const ok = (c, m) => {
  assert.ok(c, m);
  n++;
};
const has = (h, s, m) => ok(h.includes(s), m ?? `missing: ${s}`);
const lacks = (h, s, m) => ok(!h.includes(s), m ?? `unexpected: ${s}`);

const c = CASES[0];
const cardNames = Object.fromEntries(Object.entries(CARDS).map(([id, v]) => [id, v.name]));
const run = perfectRun(c);
const scores = scoreRun(c, run);
const verdict = verifyRun(c, run);
const shared = {
  c,
  cases: CASES,
  cardNames,
  labels: CATEGORY_LABELS,
  metrics: METRICS,
  modelName: "M",
  mode: "replay",
  recordedTemp: 0.7,
  promptTab: "ours",
  dspy: null,
};
const side = {
  steps: run.steps,
  modelSteps: run.steps,
  attempts: [{ steps: run.steps, verdict }],
  events: [],
  outcome: "passed_first_try",
  pending: false,
  scores,
};

// every node has a panel; the missing nodes of the agent without evals say so
const careful = buildDetails("careful", side, shared);
const simple = buildDetails(
  "simple",
  { ...side, attempts: [{ steps: run.steps, verdict: null }], outcome: null },
  shared,
);
for (const id of NODE_IDS.careful)
  ok(typeof careful[id] === "string" && careful[id].length > 20, `careful panel ${id}`);
for (const id of NODE_IDS.simple) ok(typeof simple[id] === "string" && simple[id].length > 20, `simple panel ${id}`);
for (const id of ["dataset", "key", "checks", "bar", "trace", "eval", "card", "gate"])
  has(simple[id], "MISSING", `simple ${id} is missing`);

// content
has(careful.dataset, CASES[5].query.slice(0, 20)); // the tools list at the end of every panel has its own <li> items, so count only before it
ok(
  (careful.dataset.split('<details class="stage-tools"')[0].match(/<li>/g) ?? []).length === 6,
  "six golden questions",
);
has(
  careful.key,
  "ICICI Amazon Pay or HDFC Swiggy".split(" or ").sort().join(" or ") === "HDFC Swiggy or ICICI Amazon Pay"
    ? "HDFC Swiggy or ICICI Amazon Pay"
    : "x",
  "tie names",
);
has(careful.key, "₹750");
has(careful.key, "Amazon.in");
has(careful.key, 'class="cardsmx');
has(careful.checks, METRICS[0].label);
for (const r of CHECKER_RULES) has(careful.checks, r.slice(0, 30));
has(careful.bar, "Ship only if all 7 automatic checks pass");
has(careful.ask, "Prime member");
has(careful.model, "0.2");
has(simple.model, "0.7");
has(careful.model, "ON");
has(simple.model, "OFF");
has(careful.t1, "classify_merchant");
has(careful.t1, "800 ms");
has(careful.t1, "60");
has(careful.c1, "PASS");
has(careful.answer, "HDFC Swiggy");
has(careful.trace, "&quot;tool&quot;");
has(careful.eval, "Correct final answer");
has(careful.card, "PASS");
has(careful.gate, "Ship");

// prompts: simple shows the exact prompt, careful has two tabs; the DSPy tab never says it is what the agent sent
has(simple.prompt, SYSTEM_PROMPT.slice(0, 40).replace(/&/g, "&amp;"));
has(careful.prompt, "Our prompt");
has(careful.prompt, "DSPy prompt");
has(careful.prompt, "JSON schema");
const dsp = buildDetails("careful", side, { ...shared, promptTab: "dspy", dspy: { status: "loading" } }).prompt;
has(dsp, "Loading the DSPy prompt");
const failed = buildDetails("careful", side, {
  ...shared,
  promptTab: "dspy",
  dspy: { status: "error", error: "HTTP 404" },
}).prompt;
has(failed, "could not be loaded");
has(failed, "HTTP 404");
const fake = {
  status: "ok",
  data: {
    dspyVersion: "9.9.9",
    note: "a <b>note</b>",
    variants: [
      {
        id: "zero-shot-react",
        label: "Zero",
        messages: [
          { role: "system", content: "SYS <x>" },
          { role: "user", content: "USR" },
        ],
      },
      {
        id: "few-shot",
        label: "Few",
        messages: [
          { role: "system", content: "S2" },
          { role: "user", content: "U2" },
        ],
      },
    ],
  },
};
const dh = dspyHtml(fake);
has(dh, "Generated by real DSPy 9.9.9 with a recording fake model");
has(dh, "The live agent uses the shorter prompt in the other tab");
has(dh, "SYS &lt;x&gt;");
lacks(dh, "SYS <x>");
has(dh, "a &lt;b&gt;note&lt;/b&gt;");
has(dh, "characters");

// escaping of run text
const evil = {
  ...side,
  steps: run.steps.map((s) => (s.kind === "final" ? { ...s, reply: "<img src=x onerror=1>" } : s)),
};
const ev = buildDetails("careful", evil, shared);
// the card image is a real <img class="card-art">, so look for the injected tag itself
lacks(ev.answer, "<img src=x");
lacks(ev.draft, "<img src=x");
lacks(ev.trace, "<img src=x");
has(ev.answer, "&lt;img src=x onerror=1&gt;");
has(careful.answer, 'class="card-art"', "the final card row shows the card image");
has(careful.answer, "HDFC Swiggy", "and keeps the card name as text");

// a failing score names the failing checks in the gate
const bad = { ...scores, task_success: { pass: false, reason: "wrong" } };
const g = buildDetails("careful", { ...side, scores: bad }, shared).gate;
has(g, "Blocked");
has(g, "Correct final answer");

// a typed question (checks not run, none failed) is "Cannot decide", not "Blocked"
const nk = { ...scores, task_success: { pass: null, reason: "no answer key for your own question" } };
const g2 = buildDetails("careful", { ...side, scores: nk }, shared).gate;
has(g2, "Cannot decide");
lacks(g2, "Blocked");

// pending: nothing invented
const pend = buildDetails(
  "careful",
  { ...side, steps: [], attempts: [{ steps: [], verdict: null }], pending: true, scores: null },
  shared,
);
has(pend.t1, "Not reached yet");
has(pend.c3, "reads the run when this try ends");
has(pend.gate, "Not decided yet");

// LLM judge: own node with the flow picture; the 8 checks and checks panels only point to it
ok(careful.judge.includes("You are a strict grader"), "judge: grader system prompt");
has(careful.judge, "Question: " + c.query.replace(/'/g, "&#39;"), "judge: user message built from this run");
has(careful.judge, "NOT ASKED");
has(careful.judge, 'data-hook="judge-flow"');
has(careful.judge, "Second opinion only");
lacks(careful.judge, "&amp;lt;", "judge: not double escaped");
// replay: one plain sentence, no invented grades
const NO_MODEL =
  "Recorded runs have no model to ask. Press Load model, then Ask both again, and the grader runs for real.";
has(careful.judge, NO_MODEL, "judge: replay sentence");
ok(careful.judge.indexOf(NO_MODEL) < careful.judge.indexOf('data-hook="judge-flow"'), "judge: sentence is at the top");
// live, graded: the real grades show, no replay sentence
{
  const live = { ...shared, mode: "live" };
  const graded = { ...side, judge: { all: [5, 4, "?", 4, 5], median: 4 } };
  const gs = { ...scores, rubric_judge: { pass: true, score: 4, reason: "five grades: 5, 4, ?, 4, 5" } };
  const g = buildDetails("careful", { ...graded, scores: gs }, live);
  lacks(g.judge, NO_MODEL, "judge: no replay sentence when live");
  lacks(g.judge, "NOT ASKED");
  has(g.judge, "Middle grade 4 of 5: PASS");
  has(g.judge, "NO NUMBER");
  has(g.judge, "five grades: 5, 4, ?, 4, 5");
  has(g.eval, "five grades: 5, 4, ?, 4, 5", "eval row shows the real grader result");
  has(g.eval, "asked after the answer");
  // live, not graded yet: nothing is invented
  const before = buildDetails("careful", side, live);
  has(before.judge, "NOT ASKED");
  lacks(before.judge, NO_MODEL);
  has(buildDetails("careful", { ...side, judging: true }, live).judge, "Asking the LLM judge 5 times");
}
for (const k of ["eval", "checks"]) {
  lacks(careful[k], "You are a strict grader", `${k}: no duplicate prompt`);
  has(careful[k], "Click the LLM judge box to see how it works", `${k}: pointer`);
}
has(simple.judge, "MISSING");
has(simple.judge, "Nothing here");
lacks(simple.judge, "strict grader");
ok(!simple.eval.includes("strict grader"), "agent without evals has no grader panel");
// open-source tools: every real (careful) panel has them once, MISSING boxes have none
for (const id of NODE_IDS.careful) {
  has(careful[id], "Open-source tools for this step", `careful ${id} has tools`);
  ok(careful[id].split('class="stage-tools"').length === 2, `careful ${id}: tools list exactly once`);
}
for (const id of NODE_IDS.simple) {
  const missing = simple[id].includes("<b>MISSING</b>");
  if (missing) lacks(simple[id], "Open-source tools for this step", `simple missing ${id} has no tools`);
  else has(simple[id], "Open-source tools for this step", `simple real ${id} has tools`);
}
has(careful.trace, "https://github.com/langfuse/langfuse");
lacks(simple.trace, "langfuse");
for (const [kind, d] of [
  ["careful", careful],
  ["simple", simple],
]) {
  const all = Object.values(d).join("");
  ok(!/\sid="/.test(all), `${kind}: panels add no id attributes, so no duplicate ids`);
}

// input guardrail panel
const gEv = [{ t: "guard_in_ok", attempt: 0, text: "Input guardrails passed: 4 rules" }];
const guardOk = buildDetails("careful", { ...side, events: gEv }, shared).guard;
for (const r of INPUT_RULES) {
  has(guardOk, r.label);
  has(guardOk, r.plain.replace(/'/g, "&#39;"));
}
ok((guardOk.match(/<b class="wd-ok">PASS<\/b>/g) ?? []).length === 5, "verdict line + 4 rules read PASS");
lacks(guardOk, "BLOCKED");
has(guardOk, "After the answer (output guardrails)");
for (const r of OUTPUT_RULES) {
  has(guardOk, r.label);
  has(guardOk, r.plain.replace(/'/g, "&#39;"));
}
const guardBad = buildDetails(
  "careful",
  {
    ...side,
    steps: [],
    attempts: [{ steps: [], verdict: null }],
    outcome: "blocked",
    events: [
      { t: "guard_in_fail", attempt: 0, rule: "prompt_injection", text: "This tries to change the <b>agent</b>." },
    ],
  },
  shared,
).guard;
const states = INPUT_RULES.map((r) =>
  new RegExp(`<b class="wd-(\\w+)">([A-Z ]+)</b> <b>${r.label}</b>`).exec(guardBad)?.slice(1, 3).join(":"),
);
ok(
  JSON.stringify(states) === JSON.stringify(["ok:PASS", "ok:PASS", "bad:BLOCKED", "off:NOT RUN"]),
  `per-rule words: ${states}`,
);
has(guardBad, "The model never ran");
has(guardBad, "This tries to change the &lt;b&gt;agent&lt;/b&gt;.");
lacks(guardBad, "<b>agent</b>");
has(buildDetails("careful", side, shared).guard, "The rules have not run yet");
has(buildDetails("careful", { ...side, pending: true }, shared).guard, "before the model starts");
// agent without evals: a dashed MISSING box
has(simple.guard, "MISSING");
has(simple.guard, "Nothing here");
lacks(simple.guard, INPUT_RULES[0].label);
// c3 lists the output guardrails and counts the output check
has(careful.c3, "Output guardrails (part of this check)");
for (const r of OUTPUT_RULES) has(careful.c3, r.label);
has(careful.c3, "Output guardrails passed");
const c3Bad = buildDetails(
  "careful",
  {
    ...side,
    attempts: [
      {
        steps: run.steps,
        verdict: {
          ok: false,
          problems: ["Output guardrail: The answer promised a guaranteed result."],
          checks: [{ id: "output", ok: false, label: "Output guardrails passed" }],
        },
      },
    ],
  },
  shared,
).c3;
has(c3Bad, "FAIL");
has(c3Bad, "Output guardrail: The answer promised a guaranteed result.");

// a typed question has no answer key: nothing crashes, the key panel says so
const typed = { ...c, id: "CUSTOM", custom: true, expected: null, expectedTrajectory: null };
for (const kind of ["careful", "simple"]) {
  let d;
  try {
    d = buildDetails(kind, side, { ...shared, c: typed });
  } catch (err) {
    d = null;
    console.error(err);
  }
  ok(
    d !== null && NODE_IDS[kind].every((id) => typeof d[id] === "string"),
    `${kind}: typed question builds every panel`,
  );
}
has(buildDetails("careful", side, { ...shared, c: typed }).key, "No answer key for your own question");
// ---- explain dialog input (buildExplain) ----
{
  const stateOf = { simple: "done", careful: "pass" };
  for (const kind of ["careful", "simple"]) {
    const sd = kind === "careful" ? side : { ...side, attempts: [{ steps: run.steps, verdict: null }], outcome: null };
    for (const id of NODE_IDS[kind]) {
      const x = buildExplain(kind, id, sd, shared, stateOf[kind]);
      ok(x.title && x.what && x.why, `${kind} ${id}: title, what, why`);
      ok(x.visualHtml.includes('aria-hidden="true"') && x.visualHtml.includes("<figcaption>"), `${kind} ${id}: visual`);
      ok(/<b class="xp-state">[A-Z ]+<\/b>/.test(x.thisRunHtml), `${kind} ${id}: state word in this run`);
      ok(
        x.moreSections.every((m) => !m.open),
        `${kind} ${id}: sections closed`,
      );
      const names = x.moreSections.map((m) => m.summary);
      if (id === "prompt") ok(names[0] === "Prompt", `${kind} prompt: Prompt section first`);
      else if (!x.thisRunHtml.includes("MISSING")) ok(names[0] === "Real data", `${kind} ${id}: Real data first`);
      ok(!x.moreSections.some((m) => m.html.includes("<details")), `${kind} ${id}: no nested tools details`);
    }
  }
  const ex = (id, sd = side, k = "careful", st = "pass") => buildExplain(k, id, sd, shared, st);
  // real values from the run
  has(ex("t1").thisRunHtml, "Category: amazon.");
  has(ex("t1").thisRunHtml, "&quot;merchant&quot;:&quot;Amazon&quot;", "tool input shown");
  has(ex("t2").thisRunHtml, "HDFC Swiggy ₹750", "ranking shown with card names");
  has(ex("answer", side, "careful", "done").thisRunHtml, "HDFC Swiggy, ₹750.");
  has(ex("c1").thisRunHtml, "1 of 1 rules passed.");
  has(ex("eval", side, "careful", "done").thisRunHtml, "PASS");
  has(ex("gate", side, "careful", "pass").thisRunHtml, "Ship.");
  has(ex("ask", side, "careful", "done").thisRunHtml, c.query.slice(0, 20).replace(/'/g, "&#39;"));
  {
    const h = explainHtml(ex("t2"));
    const tag = h.match(/<details class="disclose xp-sec" data-did="ask-own-ai"[^>]*>/)?.[0] ?? "";
    ok(tag && !tag.includes(" open"), "ask section exists and starts closed");
    has(h, "HDFC Swiggy ₹750", "prompt carries the run line shown in the pop-up");
  }
  // sections: raw data and tools are kept, behind closed sections
  const t1 = ex("t1");
  ok(t1.moreSections.map((m) => m.summary).join() === "Real data,Open-source tools", "t1 sections");
  has(t1.moreSections[0].html, "got back");
  has(t1.moreSections[1].html, "pydantic-ai");
  lacks(t1.moreSections[1].html, "<summary>");
  // the prompt: tabs live in the Prompt section; the agent without evals has no tabs
  const pc = ex("prompt");
  has(pc.moreSections[0].html, 'data-ptab="dspy"');
  has(pc.moreSections[0].html, "JSON schema");
  const ps = buildExplain("simple", "prompt", side, shared, "missing");
  has(ps.thisRunHtml, "MISSING");
  has(ps.moreSections[0].html, SYSTEM_PROMPT.slice(0, 40).replace(/&/g, "&amp;"));
  lacks(ps.moreSections[0].html, "data-ptab");
  has(ps.visualHtml, "xvis-missing");
  // a missing step: the word MISSING, a dashed visual, no data and no tools
  const mg = buildExplain("simple", "guard", side, shared, "missing");
  has(mg.thisRunHtml, "MISSING");
  has(mg.visualHtml, "xvis-missing");
  ok(mg.moreSections.length === 0, "missing guard: no sections");
  // escaping of run text
  const ea = buildExplain("careful", "answer", evil, shared, "done");
  lacks(ea.thisRunHtml + ea.moreSections.map((m) => m.html).join(""), "<img src=x");
  // a blocked run: the guard line carries the BLOCKED word and the reason, escaped
  const bl = buildExplain(
    "careful",
    "guard",
    {
      ...side,
      steps: [],
      attempts: [{ steps: [], verdict: null }],
      outcome: "blocked",
      events: [{ t: "guard_in_fail", rule: "prompt_injection", text: "No <b>x</b>." }],
    },
    shared,
    "blocked",
  );
  has(bl.thisRunHtml, "BLOCKED");
  has(bl.thisRunHtml, "No &lt;b&gt;x&lt;/b&gt;. The model never ran.");
  // typed question: no answer key, no crash
  has(
    buildExplain("careful", "key", side, { ...shared, c: typed }, "done").thisRunHtml,
    "No answer key for your own question.",
  );
}
console.log(`${n} checks passed`);
